#!/usr/bin/env python3
"""Flash CabControl firmware over Bluetooth LE (macOS, via bleak/CoreBluetooth).

Usage (from the repository root; uv creates tools/.venv on first run):
  uv run --project tools ble-flash --generate-secret   # once, before building
  uv run --project tools ble-flash [firmware.bin]      # first cabinet found
  uv run --project tools ble-flash --name "Cab 3" [firmware.bin]

The firmware image must be the full PlatformIO firmware.bin, which includes the
Arduino SFU bootloader in its first 64 KB. The version is read from the
CCFWVER1 marker embedded in the image and must be newer than the version
running on the device.
"""

from __future__ import annotations

import argparse
import asyncio
import hashlib
import hmac
import re
import secrets
import struct
import sys
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

# (bytes sent, total bytes, KiB/s)
ProgressFn = Callable[[int, int, float], None]
LogFn = Callable[[str], None]

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SECRET = ROOT / "include" / "ota_secret.h"
DEFAULT_FIRMWARE = ROOT / ".pio" / "build" / "nanorp2040connect" / "firmware.bin"

SERVICE_UUID = "c0de0001-cab0-4c71-9a6e-3f1d2b7e8a10"
INFO_UUID = "c0de0002-cab0-4c71-9a6e-3f1d2b7e8a10"
CONTROL_UUID = "c0de0003-cab0-4c71-9a6e-3f1d2b7e8a10"
DATA_UUID = "c0de0004-cab0-4c71-9a6e-3f1d2b7e8a10"
STATUS_UUID = "c0de0005-cab0-4c71-9a6e-3f1d2b7e8a10"

# Must match include/ota_core.h and src/ota.cpp.
PROTOCOL_VERSION = 1
AUTH_LABEL = b"CabControl-OTA-v1"
SECRET_SIZE = 32
NONCE_SIZE = 16
CMD_BEGIN, CMD_COMMIT, CMD_ABORT = 0x01, 0x02, 0x03
BEGIN_HEADER_SIZE = 2
DATA_HEADER_SIZE = 4
DATA_MAX_SIZE = 244
SFU_SIZE = 0x10000
SFU_PAGE_SIZE = 256
MIN_IMAGE_SIZE = SFU_SIZE + 0x200
MAX_IMAGE_SIZE = 0xF0000
MARKER_MAGIC = b"CCFWVER1"
STATUS_CHECK_INTERVAL = 64

STATES = {0: "IDLE", 1: "RECEIVING", 2: "VERIFYING", 3: "READY", 4: "ERROR"}
ERRORS = {
    0: "NONE",
    1: "BAD_COMMAND",
    2: "AUTH (secret mismatch)",
    3: "VERSION (image is not newer than the device firmware)",
    4: "SIZE",
    5: "STORAGE",
    6: "SEQUENCE",
    7: "HASH",
    8: "NO_SFU",
    9: "MARKER",
    10: "STATE",
    11: "TIMEOUT",
    12: "ABORTED",
}
STATE_RECEIVING, STATE_READY, STATE_ERROR = 1, 3, 4


class FlashError(Exception):
    pass


@dataclass
class Image:
    data: bytes
    version: tuple[int, int, int]
    sha256: bytes


@dataclass
class Status:
    state: int
    error: int
    received: int
    total: int

    def describe(self) -> str:
        text = STATES.get(self.state, f"state {self.state}")
        if self.state == STATE_ERROR:
            text += f": {ERRORS.get(self.error, f'error {self.error}')}"
        return text


def generate_secret(path: Path, force: bool) -> None:
    if path.exists() and not force:
        raise FlashError(f"{path} already exists (use --force to replace it; "
                         "devices running the old secret will then reject updates)")
    key = secrets.token_bytes(SECRET_SIZE)
    rows = ",\n".join(
        "    " + ", ".join(f"0x{b:02x}" for b in key[i:i + 8])
        for i in range(0, SECRET_SIZE, 8))
    path.write_text(
        "// Generated by ble-flash --generate-secret. Do not commit.\n"
        "#ifndef OTA_SECRET_H\n#define OTA_SECRET_H\n\n#include <stdint.h>\n\n"
        f"static const uint8_t OTA_SECRET[{SECRET_SIZE}] = {{\n{rows}}};\n\n"
        "#endif\n")
    print(f"Wrote {path}. Rebuild and flash over USB once so the device knows it.")


def load_secret(path: Path) -> bytes:
    if not path.exists():
        raise FlashError(f"{path} not found; run with --generate-secret first")
    match = re.search(r"OTA_SECRET\s*\[\s*\d*\s*\]\s*=\s*\{([^}]*)\}", path.read_text())
    if match is None:
        raise FlashError(f"Could not find OTA_SECRET in {path}")
    values = [int(v, 0) for v in re.findall(r"0[xX][0-9a-fA-F]+|\d+", match.group(1))]
    if len(values) != SECRET_SIZE or any(v > 0xFF for v in values):
        raise FlashError(f"OTA_SECRET in {path} must be {SECRET_SIZE} bytes")
    return bytes(values)


def load_image(path: Path) -> Image:
    if not path.exists():
        raise FlashError(f"{path} not found; build with `pio run -e nanorp2040connect`")
    data = path.read_bytes()
    if not MIN_IMAGE_SIZE <= len(data) <= MAX_IMAGE_SIZE:
        raise FlashError(f"Image size {len(data)} B is outside "
                         f"{MIN_IMAGE_SIZE}..{MAX_IMAGE_SIZE} B")
    # Same rule as the SFU bootloader: signature inside a 256-byte page of the
    # first 64 KB, otherwise it refuses to install the image.
    if not any(b"SFU version" in data[i:i + SFU_PAGE_SIZE]
               for i in range(0, SFU_SIZE, SFU_PAGE_SIZE)):
        raise FlashError("Image does not contain the SFU bootloader")
    offsets = [m.start() for m in re.finditer(re.escape(MARKER_MAGIC), data)
               if m.start() >= SFU_SIZE]
    if len(offsets) != 1 or offsets[0] + len(MARKER_MAGIC) + 3 > len(data):
        raise FlashError(f"Expected exactly one version marker, found {len(offsets)}")
    start = offsets[0] + len(MARKER_MAGIC)
    version = tuple(data[start:start + 3])
    return Image(data, version, hashlib.sha256(data).digest())


def build_begin_body(secret: bytes, nonce: bytes, image: Image) -> bytes:
    signed = struct.pack("<I3B", len(image.data), *image.version) + image.sha256
    tag = hmac.new(secret, AUTH_LABEL + nonce + signed, hashlib.sha256).digest()
    return signed + tag


def parse_status(raw: bytes) -> Status:
    state, error, received, total = struct.unpack("<BBII", bytes(raw[:10]))
    return Status(state, error, received, total)


def version_text(version: tuple[int, ...]) -> str:
    return ".".join(str(v) for v in version)


async def find_device(args: argparse.Namespace):
    from bleak import BleakScanner

    print("Scanning for CabControl...")
    if args.address:
        device = await BleakScanner.find_device_by_address(args.address, timeout=args.scan_timeout)
    else:
        def matches(device, adv) -> bool:
            uuids = [u.lower() for u in adv.service_uuids]
            name = adv.local_name or device.name
            return SERVICE_UUID in uuids and args.name in (None, name)

        device = await BleakScanner.find_device_by_filter(matches, timeout=args.scan_timeout)
    if device is None:
        raise FlashError("Device not found. Check that it is powered and in range, and "
                         "the OLED 'BLE' page does not show 'BLE start fail'.")
    return device


async def read_status(client) -> Status:
    return parse_status(await client.read_gatt_char(STATUS_UUID))


class ConsoleProgress:
    """Single-line progress for the command line."""

    def __init__(self) -> None:
        self.active = False

    def __call__(self, sent: int, total: int, rate: float) -> None:
        self.active = True
        print(f"\r  {sent * 100 // total:3d}%  {sent}/{total} B  {rate:.1f} KiB/s",
              end="", flush=True)

    def end_line(self) -> None:
        if self.active:
            print()
            self.active = False


async def flash(args: argparse.Namespace, secret: bytes, image: Image) -> None:
    from bleak import BleakClient

    device = await find_device(args)
    print(f"Connecting to {device.name or 'CabControl'} ({device.address})...")
    progress = ConsoleProgress()

    def log(message: str) -> None:
        progress.end_line()
        print(message)

    async with BleakClient(device) as client:
        try:
            await transfer(client, secret, image, progress, log)
        finally:
            progress.end_line()


async def transfer(client, secret: bytes, image: Image,
                   progress: ProgressFn | None = None, log: LogFn = print) -> None:
    """Uploads and verifies the image. On success the device reboots ~1 s later
    to install it, which disconnects the client. Cancelling (or any error
    during the data phase) sends ABORT so the device drops the partial file."""
    info = bytes(await client.read_gatt_char(INFO_UUID))
    if len(info) < 4 + NONCE_SIZE or info[0] != PROTOCOL_VERSION:
        raise FlashError(f"Unsupported OTA protocol on device: {info[:1].hex()}")
    device_version = tuple(info[1:4])
    nonce = info[4:4 + NONCE_SIZE]
    log(f"Device firmware {version_text(device_version)}, "
        f"image {version_text(image.version)} ({len(image.data)} B)")
    if image.version <= device_version:
        raise FlashError("Image is not newer than the device firmware; "
                         "bump PARAMS_VERSION_* in include/params.h")

    # ArduinoBLE has no long-write support, so every write must fit the MTU.
    max_write = min(client.mtu_size - 3, DATA_MAX_SIZE)
    if max_write <= DATA_HEADER_SIZE:
        raise FlashError(f"ATT MTU {client.mtu_size} is too small")

    body = build_begin_body(secret, nonce, image)
    fragment_size = max_write - BEGIN_HEADER_SIZE
    for offset in range(0, len(body), fragment_size):
        fragment = body[offset:offset + fragment_size]
        await client.write_gatt_char(
            CONTROL_UUID, bytes([CMD_BEGIN, offset]) + fragment, response=True)
    status = await read_status(client)
    if status.state != STATE_RECEIVING:
        raise FlashError(f"Device refused the update: {status.describe()}")

    chunk_size = max_write - DATA_HEADER_SIZE
    total = len(image.data)
    started = time.monotonic()
    try:
        for index, offset in enumerate(range(0, total, chunk_size)):
            payload = image.data[offset:offset + chunk_size]
            await client.write_gatt_char(
                DATA_UUID, struct.pack("<I", offset) + payload, response=True)
            sent = offset + len(payload)
            if (index + 1) % STATUS_CHECK_INTERVAL == 0 or sent == total:
                status = await read_status(client)
                if status.state != STATE_RECEIVING or status.received != sent:
                    raise FlashError(f"Transfer failed at {sent} B: {status.describe()}")
            if progress is not None:
                progress(sent, total, sent / max(time.monotonic() - started, 1e-3) / 1024)
    except BaseException:
        try:
            await client.write_gatt_char(CONTROL_UUID, bytes([CMD_ABORT]), response=True)
        except Exception:
            pass
        raise

    log("Verifying on device...")
    await client.write_gatt_char(CONTROL_UUID, bytes([CMD_COMMIT]), response=True)
    status = await read_status(client)
    if status.state != STATE_READY:
        raise FlashError(f"Verification failed: {status.describe()}")
    log(f"Verified. The device reboots and installs {version_text(image.version)}.")


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("firmware", nargs="?", type=Path, default=DEFAULT_FIRMWARE,
                        help=f"firmware image (default: {DEFAULT_FIRMWARE.relative_to(ROOT)})")
    parser.add_argument("--secret", type=Path, default=DEFAULT_SECRET,
                        help=f"secret header (default: {DEFAULT_SECRET.relative_to(ROOT)})")
    parser.add_argument("--generate-secret", action="store_true",
                        help="create a new random secret header and exit")
    parser.add_argument("--force", action="store_true",
                        help="allow --generate-secret to replace an existing secret")
    parser.add_argument("--name",
                        help="identification name of the cabinet (default: first one found)")
    parser.add_argument("--address",
                        help="connect to this BLE address/UUID instead of scanning by name")
    parser.add_argument("--scan-timeout", type=float, default=15.0,
                        help="seconds (default: %(default)s)")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    try:
        if args.generate_secret:
            generate_secret(args.secret, args.force)
            return 0
        secret = load_secret(args.secret)
        image = load_image(args.firmware)
        asyncio.run(flash(args, secret, image))
    except FlashError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        print("aborted", file=sys.stderr)
        return 130
    return 0


if __name__ == "__main__":
    sys.exit(main())
